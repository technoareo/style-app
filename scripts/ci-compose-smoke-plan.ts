export type SmokeNames = { runId: string; project: string };

export function makeRunId(random: (n: number) => Buffer = randomBytes): string {
  return random(5).toString("hex");
}

export function smokeNames(runId: string): SmokeNames {
  if (!/^[0-9a-f]{6,16}$/.test(runId)) throw new Error("Invalid smoke run id.");
  return { runId, project: `${SMOKE_PREFIX}${runId}` };
}

/** Same rule as the shell `case` in compose.yaml: 4 to 6 digits, no leading zero, at most 120000. */
export function bodyTimeoutAccepted(value: string): boolean {
  return /^[1-9][0-9]{3,5}$/.test(value) && Number(value) <= 120_000;
}

/** The proxy's Caddy cap: ceil(ms / 1000) + 2 seconds, the shell's `(ms + 999) / 1000 + 2`. */
export function proxyCapSeconds(ms: number): number {
  return Math.floor((ms + 999) / 1000) + 2;
}

// --- generated files -------------------------------------------------------------

/** The project `.env` next to compose.yaml: the domain, and optionally the one timeout variable (raw text, so invalid values can be tried). */
export function projectEnvFile(o: { domain?: string | null; bodyTimeout?: string | null } = {}): string {
  const domain = o.domain === undefined ? SMOKE_DOMAIN : o.domain;
  return (
    [
      "# Generated by scripts/ci-compose-smoke.ts. Non-secret Compose variables only.",
      ...(domain === null ? [] : [`STYLE_DOMAIN=${domain}`]),
      ...(o.bodyTimeout === undefined || o.bodyTimeout === null ? [] : [`STYLE_BODY_READ_TIMEOUT_MS=${o.bodyTimeout}`]),
    ].join("\n") + "\n"
  );
}

/** `.env.production` for the app. The secret is random per run; SMTP is a placeholder nothing connects to. */
export function appEnvFile(o: { authSecret: string; extraLines?: string[] }): string {
  if (o.authSecret.length < 32) throw new Error("AUTH_SECRET must be at least 32 characters.");
  return (
    [
      `AUTH_SECRET=${o.authSecret}`,
      `APP_URL=${SMOKE_APP_URL}`,
      "SMTP_URL=smtp://127.0.0.1:2525",
      `MAIL_FROM=Style Studio <no-reply@${SMOKE_DOMAIN}>`,
      `STYLE_AUTH_LOCK_MS=${AUTH_LOCK_MS}`,
      ...(o.extraLines ?? []),
    ].join("\n") + "\n"
  );
}

export const generateAuthSecret = (random: (n: number) => Buffer = randomBytes): string =>
  random(36).toString("base64url");

/** The smoke test sets these itself; a leftover shell value would silently win over the project `.env`. */
export function assertCleanEnvironment(env: Record<string, string | undefined>): void {
  const bad = ["STYLE_DOMAIN", "STYLE_BODY_READ_TIMEOUT_MS", "STYLE_COMPOSE_BODY_READ_TIMEOUT_MS", "STYLE_PROXY_BODY_READ_TIMEOUT_S"].filter(
    (k) => env[k] !== undefined,
  );
  if (bad.length)
    throw new Error(`Unset ${bad.join(", ")} before running the Compose smoke test: a shell value would override the project .env it tests.`);
}

// --- docker compose argument lists ------------------------------------------------

export function composeArgs(project: string, dir: string, rest: string[], withOverride = true): string[] {
  return [
    "compose",
    "-p",
    project,
    "--project-directory",
    dir,
    "-f",
    path.join(dir, "compose.yaml"),
    ...(withOverride ? ["-f", path.join(dir, "compose.smoke.yaml")] : []),
    ...rest,
  ];
}

