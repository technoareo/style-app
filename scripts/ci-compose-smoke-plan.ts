/**
 * Build 023: the pure, deterministic part of the CI Docker Compose + Caddy
 * smoke test (scripts/ci-compose-smoke.ts). It only BUILDS argument lists, env
 * files and in-container probe programs, and compares plain data; it never
 * starts anything. tests/ciComposeSmoke023.test.ts pins the contract below.
 *
 *  - The shipped compose.yaml and deploy/Caddyfile are COPIED byte for byte
 *    into a throw-away project folder and merged with deploy/ci/compose.smoke.yaml.
 *    The override may only change the allow-listed paths in ALLOWED_OVERRIDE_DIFFS;
 *    the runner compares `docker compose config` with and without it.
 *  - Local TLS needs no public domain and no certificate authority account:
 *    the site name is a `.localhost` name, which Caddy always serves from its
 *    own internal CA. It is not `localhost` itself because the application
 *    refuses that name as a public APP_URL.
 *  - Nothing real is reached: the model is the CI mock, the mail worker never
 *    starts, and the SMTP value is a placeholder nothing connects to.
 */

