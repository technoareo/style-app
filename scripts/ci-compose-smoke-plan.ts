/** Cleanup by name, for what `down` could not remove or a crashed run left (the project name carries the run id). */
export function listByNameArgs(kind: "container" | "volume" | "network", run?: SmokeNames): string[] {
  const filter = `name=${run ? run.project : SMOKE_PREFIX}`;
  if (kind === "container") return ["ps", "-aq", "--filter", filter];
  if (kind === "volume") return ["volume", "ls", "-q", "--filter", filter];
  return ["network", "ls", "-q", "--filter", filter];
}

export function parseComposeVersion(text: string): [number, number, number] | null {
  const m = /v?(\d+)\.(\d+)\.(\d+)/.exec(text);
  return m ? [Number(m[1]), Number(m[2]), Number(m[3])] : null;
}

/** `!override` in compose.smoke.yaml needs Compose 2.24 or newer. */
export function composeSupportsOverride(text: string): boolean {
  const v = parseComposeVersion(text);
  return v !== null && (v[0] > 2 || (v[0] === 2 && v[1] >= 24));
}

// --- "the override changes only what it says" ---------------------------------------

/**
 * Paths of `docker compose config --format json` that deploy/ci/compose.smoke.yaml
 * is allowed to change. A trailing dot allows everything below. Anything else
 * that differs between the shipped file alone and shipped file plus override
 * fails the run: the commands, healthchecks, environment, mounts, security
 * options and capabilities of `app` and `proxy` are not on this list.
 */
export const ALLOWED_OVERRIDE_DIFFS = [
  "services.app.image",
  "services.app.pull_policy",
  "services.app.restart",
  "services.worker.image",
  "services.worker.pull_policy",
  "services.mailer.image",
  "services.mailer.pull_policy",
  "services.proxy.restart",
  "services.proxy.ports",
  "services.ollama.",
] as const;

const isObject = (v: unknown): v is Record<string, unknown> => typeof v === "object" && v !== null && !Array.isArray(v);

/** Leaf paths where two parsed JSON documents differ (arrays and scalars are leaves). */
export function diffPaths(a: unknown, b: unknown, prefix = ""): string[] {
  if (isObject(a) && isObject(b)) {
    const keys = new Set([...Object.keys(a), ...Object.keys(b)]);
    return [...keys].flatMap((k) => diffPaths(a[k], b[k], prefix ? `${prefix}.${k}` : k));
  }
  return JSON.stringify(a) === JSON.stringify(b) ? [] : [prefix];
}

export function unexpectedDiffs(paths: readonly string[]): string[] {
  return paths.filter((p) => !ALLOWED_OVERRIDE_DIFFS.some((rule) => (rule.endsWith(".") ? p.startsWith(rule) : p === rule)));
}

// --- header comparison --------------------------------------------------------------

/** Headers that legitimately differ between a direct and a proxied answer and carry no behaviour we compare. */
const IGNORED = new Set(["date", "connection", "keep-alive", "transfer-encoding", "content-length"]);
/** Headers the proxy may ADD (Caddy's own, plus the five the Caddyfile sets). */
const MAY_ADD = new Set([...Object.keys(SECURITY_HEADERS), "server", "via"]);

export function headerMap(raw: readonly string[]): Map<string, string[]> {
  const map = new Map<string, string[]>();
  for (let i = 0; i + 1 < raw.length; i += 2) {
    const name = raw[i].toLowerCase();
    map.set(name, [...(map.get(name) ?? []), raw[i + 1]]);
  }
  return map;
}

const tokens = (values: string[]) => values.join(",").split(",").map((t) => t.trim().toLowerCase()).filter(Boolean);

/**
 * Problems found comparing a direct answer's headers with the same answer
 * through the proxy: every direct header must arrive with the identical
 * value(s) (so a duplicated `Cache-Control` is caught), the proxy may add only
 * its own and the Caddyfile's, and an error must close the connection.
 */
export function compareHeaders(direct: readonly string[], proxied: readonly string[], opts: { expectClose: boolean }): string[] {
  const d = headerMap(direct);
  const p = headerMap(proxied);
  const problems: string[] = [];
  for (const [name, values] of d) {
    if (IGNORED.has(name)) continue;
    const got = p.get(name);
    if (!got) problems.push(`header "${name}" was lost through the proxy`);
    else if (name === "vary") {
      const have = new Set(tokens(got));
      for (const t of tokens(values)) if (!have.has(t)) problems.push(`Vary lost "${t}"`);
    } else if (JSON.stringify(got) !== JSON.stringify(values))
      problems.push(`header "${name}" changed: direct ${JSON.stringify(values)} vs proxied ${JSON.stringify(got)}`);
  }
  for (const [name, values] of p) {
    if (IGNORED.has(name) || d.has(name)) continue;
    if (name === "vary" && tokens(values).every((t) => t === "accept-encoding")) continue;
    if (!MAY_ADD.has(name)) problems.push(`the proxy added an unexpected header "${name}"`);
  }
  for (const [name, values] of p)
    if (values.length > 1 && name !== "set-cookie" && (d.get(name)?.length ?? 1) < values.length)
      problems.push(`header "${name}" appears ${values.length} times through the proxy`);
  problems.push(...securityHeaderProblems(proxied));
  const connection = tokens(p.get("connection") ?? []);
  if (opts.expectClose && !connection.includes("close")) problems.push("the proxied error answer did not say Connection: close");
  if (!opts.expectClose && connection.includes("close")) problems.push("a successful answer unexpectedly said Connection: close");
  return problems;
}

/** The five Caddyfile headers must be present once with exactly the shipped value. */
export function securityHeaderProblems(proxied: readonly string[]): string[] {
  const p = headerMap(proxied);
  return Object.entries(SECURITY_HEADERS).flatMap(([name, value]) => {
    const got = p.get(name);
    if (!got) return [`missing security header "${name}"`];
    return got.length === 1 && got[0] === value ? [] : [`security header "${name}" is ${JSON.stringify(got)}, expected ${JSON.stringify(value)}`];
  });
}

// --- Caddy's running configuration ---------------------------------------------------

export type CaddyTimeoutFacts = { protocols: string[]; readBodyNs: number[]; readHeaderNs: number[] };

/**
 * Reads the timeouts of the server that listens on :443 out of Caddy's admin
 * answer for /config/apps/http/servers. The JSON key names are not asserted
 * (they differ between Caddy versions); the VALUES must be present under a key
 * that says "read" (body) or "header". The whole timeout object is returned for
 * the log so the first CI run records the real key names.
 */
export function caddyTimeoutFacts(servers: unknown): { facts: CaddyTimeoutFacts; raw: Record<string, unknown> } {
  if (!isObject(servers)) throw new Error("Caddy's server list was not an object.");
  const tls = Object.values(servers).find((s) => isObject(s) && Array.isArray(s.listen) && s.listen.some((l) => String(l).endsWith(":443")));
  if (!isObject(tls)) throw new Error("Caddy has no server listening on :443.");
  const raw: Record<string, unknown> = {};
  const readBodyNs: number[] = [];
  const readHeaderNs: number[] = [];
  for (const [k, v] of Object.entries(tls)) {
    if (typeof v !== "number" || !/read|timeout/i.test(k)) continue;
    raw[k] = v;
    if (/header/i.test(k)) readHeaderNs.push(v);
    else if (/read/i.test(k)) readBodyNs.push(v);
  }
  const protocols = Array.isArray(tls.protocols) ? tls.protocols.map(String) : [];
  return { facts: { protocols, readBodyNs, readHeaderNs }, raw: { ...raw, protocols } };
}

export function caddyTimeoutProblems(facts: CaddyTimeoutFacts, appMs: number): string[] {
  const cap = proxyCapSeconds(appMs) * 1e9;
  const problems: string[] = [];
  if (JSON.stringify(facts.protocols) !== JSON.stringify(["h1"])) problems.push(`Caddy protocols are ${JSON.stringify(facts.protocols)}, expected ["h1"]`);
  if (!facts.readBodyNs.includes(cap)) problems.push(`no Caddy read timeout equals the derived ${cap / 1e9} s (found ${JSON.stringify(facts.readBodyNs)})`);
  if (!facts.readHeaderNs.includes(10e9)) problems.push(`no Caddy header timeout equals 10 s (found ${JSON.stringify(facts.readHeaderNs)})`);
  return problems;
}

/** The accepted window for a stalled upload's 408: after most of the app deadline, strictly before the proxy cap. */
export function stalledWindowMs(appMs: number): { min: number; max: number } {
  return { min: Math.floor(appMs * 0.9), max: proxyCapSeconds(appMs) * 1000 - 100 };
}

